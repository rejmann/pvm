//go:build linux || darwin

package symlink

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/rejmann/pvm/internal/home"
)

// EnsureShim (re)writes the php shim script in the shim directory of h.
func EnsureShim(h *home.Dir) error {
	exe, err := os.Executable()
	if err != nil {
		return fmt.Errorf("locate pvm executable: %w", err)
	}
	if resolved, err := filepath.EvalSymlinks(exe); err == nil {
		exe = resolved
	}
	return writeShim(filepath.Join(h.ShimDir(), "php"), exe)
}

// shimScript delegates to `pvm shim php`, which picks the version for the
// current directory ($PVM_VERSION, .php-version, then the global version).
func shimScript(pvmExe string) string {
	return "#!/bin/sh\n" +
		"# Managed by pvm — do not edit. Regenerated by `pvm use`.\n" +
		"exec " + shellQuote(pvmExe) + " shim php \"$@\"\n"
}

func writeShim(path, pvmExe string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return err
	}
	tmp := path + ".tmp"
	os.Remove(tmp)
	if err := os.WriteFile(tmp, []byte(shimScript(pvmExe)), 0755); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}

func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}
